"""Evaluation harness: retrieval quality, refusal behaviour, and the Q&A log.

Reports two families of metric, because they fail independently:

  RETRIEVAL   Hit@1, Hit@4, MRR against the expected source document. Measures
              whether the right passage was found at all. A pipeline can score
              perfectly here and still answer badly.

  REFUSAL     Precision and recall over the answerable/unanswerable split.
              Recall matters more than raw accuracy in this system: a confident
              wrong answer costs a user far more than an unnecessary "I don't
              know", so the threshold is deliberately tuned toward refusing.

Also emits eval/qa_log.md, which is a required deliverable.

Run:  python eval/run_eval.py
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from rag.answer import RagPipeline          # noqa: E402
from rag.config import settings             # noqa: E402

HERE = Path(__file__).resolve().parent


def load_questions() -> list[dict]:
    return yaml.safe_load((HERE / "questions.yaml").read_text(encoding="utf-8"))


def evaluate(pipeline: RagPipeline, questions: list[dict]) -> list[dict]:
    rows = []
    for i, q in enumerate(questions, start=1):
        print(f"  [{i}/{len(questions)}] {q['question']}")
        result = pipeline.answer(q["question"])
        docs = [h.chunk.doc for h in result.hits]

        expect_doc = q.get("expect_doc")
        rank = None
        if expect_doc and expect_doc in docs:
            rank = docs.index(expect_doc) + 1

        contains = q.get("expect_contains") or []
        missing = [s for s in contains if s.lower() not in result.text.lower()]

        rows.append(
            {
                "q": q,
                "result": result,
                "rank": rank,
                "hit1": rank == 1,
                "hit4": rank is not None,
                "rr": (1.0 / rank) if rank else 0.0,
                "content_ok": not missing,
                "missing": missing,
                "flag_ok": (
                    result.citations
                    and any(c.truncated for c in result.citations)
                    if q.get("expect_truncation_flag")
                    else True
                ),
            }
        )
    return rows


def metrics(rows: list[dict]) -> dict:
    answerable = [r for r in rows if r["q"]["answerable"]]
    unanswerable = [r for r in rows if not r["q"]["answerable"]]

    scored = [r for r in answerable if r["q"].get("expect_doc")]
    n = max(len(scored), 1)

    # Refusal confusion matrix, from the perspective "refusal is the positive".
    tp = sum(1 for r in unanswerable if not r["result"].answered)   # correctly refused
    fn = sum(1 for r in unanswerable if r["result"].answered)       # fabricated
    fp = sum(1 for r in answerable if not r["result"].answered)     # over-refused
    tn = sum(1 for r in answerable if r["result"].answered)

    return {
        "hit1": sum(r["hit1"] for r in scored) / n,
        "hit4": sum(r["hit4"] for r in scored) / n,
        "mrr": sum(r["rr"] for r in scored) / n,
        "content_ok": sum(r["content_ok"] for r in answerable) / max(len(answerable), 1),
        "refusal_precision": tp / max(tp + fp, 1),
        "refusal_recall": tp / max(tp + fn, 1),
        "answered_correctly_refused": f"{tp}/{len(unanswerable)}",
        "over_refused": f"{fp}/{len(answerable)}",
        "tp": tp, "fp": fp, "fn": fn, "tn": tn,
        "n_answerable": len(answerable),
        "n_unanswerable": len(unanswerable),
        "avg_latency_ms": sum(r["result"].latency_ms for r in rows) // max(len(rows), 1),
    }


def write_log(rows: list[dict], m: dict, path: Path) -> None:
    out: list[str] = []
    out.append("# Sample Q&A Log\n")
    out.append(
        f"Generated by `python eval/run_eval.py` against {m['n_answerable']} answerable "
        f"and {m['n_unanswerable']} unanswerable questions.\n"
    )
    out.append(
        f"Models: `{settings.embedding_model}` (embeddings), `{settings.llm_model}` "
        f"(rerank + answer). Refusal threshold tau = {settings.relevance_threshold}.\n"
    )

    out.append("\n## Metrics\n")
    out.append("| Metric | Value | Reading |")
    out.append("|---|---|---|")
    out.append(f"| Hit@1 | {m['hit1']:.0%} | Expected document ranked first |")
    out.append(f"| Hit@4 | {m['hit4']:.0%} | Expected document in the 4 shown to the LLM |")
    out.append(f"| MRR | {m['mrr']:.2f} | Mean reciprocal rank of the expected document |")
    out.append(f"| Key-fact accuracy | {m['content_ok']:.0%} | Answer contains the expected value |")
    out.append(f"| Refusal recall | {m['refusal_recall']:.0%} | Unanswerable questions correctly refused ({m['answered_correctly_refused']}) |")
    out.append(f"| Refusal precision | {m['refusal_precision']:.0%} | Refusals that were genuinely unanswerable |")
    out.append(f"| Over-refusals | {m['over_refused']} | Answerable questions wrongly refused |")
    out.append(f"| Avg latency | {m['avg_latency_ms']} ms | Retrieve + rerank + answer + verify |")

    for label, subset in (
        ("Answerable questions", [r for r in rows if r["q"]["answerable"]]),
        ("Unanswerable questions", [r for r in rows if not r["q"]["answerable"]]),
    ):
        out.append(f"\n## {label}\n")
        for i, r in enumerate(subset, start=1):
            q, res = r["q"], r["result"]
            out.append(f"### {i}. {q['question']}\n")
            if q.get("tests"):
                out.append(f"> **Tests:** {q['tests'].strip()}\n")
            status = "ANSWERED" if res.answered else f"REFUSED ({res.refusal_reason})"
            out.append(f"**Status:** {status} &nbsp;|&nbsp; top relevance score: {res.top_score:.1f}\n")
            out.append(f"**Answer:**\n\n{res.text}\n")
            if res.citations:
                out.append("**Sources:**\n")
                for c in res.citations:
                    sec = f" - {c.section}" if c.section else ""
                    trunc = "  *(clipped in source PDF)*" if c.truncated else ""
                    out.append(f"- `[{c.marker}]` {c.doc}, page {c.page}{sec}{trunc}")
                out.append("")
            if res.warnings:
                for w in res.warnings:
                    out.append(f"> WARNING: {w}\n")
            if r["missing"]:
                out.append(f"> Expected but not found in the answer: `{r['missing']}`\n")
            out.append("")

    path.write_text("\n".join(out), encoding="utf-8")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(HERE / "qa_log.md"))
    args = ap.parse_args()

    questions = load_questions()
    print(f"Evaluating {len(questions)} questions...")
    pipeline = RagPipeline()
    rows = evaluate(pipeline, questions)
    m = metrics(rows)

    print("\n" + "=" * 60)
    print(f"  Hit@1              {m['hit1']:.0%}")
    print(f"  Hit@4              {m['hit4']:.0%}")
    print(f"  MRR                {m['mrr']:.2f}")
    print(f"  Key-fact accuracy  {m['content_ok']:.0%}")
    print(f"  Refusal recall     {m['refusal_recall']:.0%}  ({m['answered_correctly_refused']})")
    print(f"  Refusal precision  {m['refusal_precision']:.0%}")
    print(f"  Over-refused       {m['over_refused']}")
    print(f"  Avg latency        {m['avg_latency_ms']} ms")
    print("=" * 60)

    for r in rows:
        res, q = r["result"], r["q"]
        bad = (q["answerable"] and not res.answered) or (not q["answerable"] and res.answered)
        if bad or r["missing"] or not r["flag_ok"]:
            tag = "FAIL" if bad else "warn"
            print(f"  [{tag}] {q['question']}"
                  + (f" -> missing {r['missing']}" if r["missing"] else "")
                  + ("" if r["flag_ok"] else " -> truncation flag not surfaced"))

    write_log(rows, m, Path(args.out))
    print(f"\nWrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
